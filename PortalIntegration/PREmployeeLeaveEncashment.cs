        public SysOperationResult_BOL create(DataTable _objDT)
        {
            DataTable dataTable = _objDT;
            SysOperationResult_BOL objBOL = new SysOperationResult_BOL();
            try
            {
                string dataAreaId = SessionVariables.getUserCurrentDataAreaId();

                var authenticationHeader = OAuthHelper.getAuthenticationHeader();
                var serviceUriString = SoapHelper.GetSoapServiceUriString(serviceName, ClientConfiguration.Default.UriString);

                var endpointAddress = new EndpointAddress(serviceUriString);
                var binding = SoapHelper.GetBinding();

                var client = new PREmployeeLeaveEncashmentSvcClient(binding, endpointAddress);
                var channel = client.InnerChannel;

                using (OperationContextScope operationContextScope = new OperationContextScope(channel))
                {
                    HttpRequestMessageProperty requestMessage = new HttpRequestMessageProperty();
                    requestMessage.Headers[OAuthHelper.OAuthHeader] = authenticationHeader;
                    OperationContext.Current.OutgoingMessageProperties[HttpRequestMessageProperty.Name] = requestMessage;

                    CallContext callContext = new CallContext();
                    callContext.MessageId = Guid.NewGuid().ToString();
                    callContext.Company = dataAreaId;

                    foreach (DataRow dataRow in dataTable.Rows)
                    {
                        PREmployeeLeaveEncashmentContract encashmentContract = new PREmployeeLeaveEncashmentContract();

                        encashmentContract.EmployeeId = dataRow["EmployeeId"]?.ToString();

                        encashmentContract.EntitlementCode = dataRow["EntitlementCode"]?.ToString();

                        if (dataRow["RequestDate"] != DBNull.Value)
                            encashmentContract.RequestDate =
                                Convert.ToDateTime(dataRow["RequestDate"]);

                        encashmentContract.BalanceBeforeApplication =
                            Convert.ToDecimal(dataRow["LeaveBalanceBefore"]);

                        encashmentContract.LeavesToEncashed =
                            Convert.ToDecimal(dataRow["LeavesToBeEncashed"]);

                        //encashmentContract.EarningAmount =
                        //    Convert.ToDecimal(dataRow["EarningAmount"]);

                        encashmentContract.RemainingBalance =
                            Convert.ToDecimal(dataRow["RemainingBalance"]);


                        GeneralContract results = ((PREmployeeLeaveEncashmentSvc)channel).createAsync(new create(callContext, encashmentContract)).Result.result;
                        objBOL = SysOperationResults.operationResult<GeneralContract>(results);

                    }
                }

            }
            catch (Exception ex)
            {
                SysErrorLog objErrorLog = new SysErrorLog();
                System.Reflection.MethodBase currentMethod = System.Reflection.MethodBase.GetCurrentMethod();
                string currentMethodName = currentMethod.DeclaringType.FullName;
                objErrorLog.write(currentMethodName, ex);
            }
            finally
            {
            }
            return objBOL;
        }

