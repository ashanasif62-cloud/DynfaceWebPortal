        public SysOperationResult_BOL create(DataTable _objDT)
        {
            DataTable dataTable = _objDT;
            SysOperationResult_BOL objBOL = new SysOperationResult_BOL();
            try
            {
                string dataAreaId = SessionVariables.getUserCurrentDataAreaId();

                var authenticationHeader = OAuthHelper.getAuthenticationHeader();
                var serviceUriString = SoapHelper.GetSoapServiceUriString(serviceName, ClientConfiguration.Default.UriString);

                var endpointAddress = new EndpointAddress(serviceUriString);
                var binding = SoapHelper.GetBinding();

                var client = new TransferJournalLinesSvcClient(binding, endpointAddress);
                var channel = client.InnerChannel;

                using (OperationContextScope operationContextScope = new OperationContextScope(channel))
                {
                    HttpRequestMessageProperty requestMessage = new HttpRequestMessageProperty();
                    requestMessage.Headers[OAuthHelper.OAuthHeader] = authenticationHeader;
                    OperationContext.Current.OutgoingMessageProperties[HttpRequestMessageProperty.Name] = requestMessage;

                    CallContext callContext = new CallContext();
                    callContext.MessageId = Guid.NewGuid().ToString();
                    callContext.Company = dataAreaId;

                    foreach (DataRow dataRow in dataTable.Rows)
                    {
                        TransferJournalLinesContract transferjournallines = new TransferJournalLinesContract();

                        transferjournallines.RecIdHeader = Convert.ToInt64(dataRow["RecId"]);  // RecId from session
                        transferjournallines.ItemId = dataRow["ItemId"].ToString();
                        transferjournallines.FromInventSiteId = dataRow["FromSite"].ToString();
                        transferjournallines.FromInventLocationId = dataRow["FromWarehouse"].ToString();
                        transferjournallines.ToInventSiteId = dataRow["ToSite"].ToString();
                        transferjournallines.ToInventLocationId = dataRow["ToWarehouse"].ToString();

                        transferjournallines.FromInventBatchId = dataRow["FromInventBatchId"].ToString();
                        transferjournallines.FromInventSerialId = dataRow["FromInventSerialId"].ToString();
                        transferjournallines.FromInventConfigId = dataRow["FromInventConfigId"].ToString();
                        transferjournallines.FromInventSizeId = dataRow["FromInventSizeId"].ToString();
                        transferjournallines.FromInventColorId = dataRow["FromInventColorId"].ToString();
                        transferjournallines.FromInventStyleId = dataRow["FromInventStyleId"].ToString();
                        transferjournallines.FromWMSLocationId = dataRow["FromWMSLocationId"].ToString();

                        transferjournallines.ToInventBatchId = dataRow["ToInventBatchId"].ToString();
                        transferjournallines.ToInventSerialId = dataRow["ToInventSerialId"].ToString();
                        transferjournallines.ToInventConfigId = dataRow["ToInventConfigId"].ToString();
                        transferjournallines.ToInventSizeId = dataRow["ToInventSizeId"].ToString();
                        transferjournallines.ToInventColorId = dataRow["ToInventColorId"].ToString();
                        transferjournallines.ToInventStyleId = dataRow["ToInventStyleId"].ToString();
                        transferjournallines.ToWMSLocationId = dataRow["ToWMSLocationId"].ToString();

                        // Assign PurchQty safely
                        decimal qty = 0;
                        decimal.TryParse(dataRow["Qty"].ToString(), out qty);
                        transferjournallines.Qty = qty;

                        decimal unitQty = 0;
                        decimal.TryParse(dataRow["UnitQuantity"].ToString(), out unitQty);
                        transferjournallines.UnitQty = unitQty;


                        GeneralContract results = ((TransferJournalLinesSvc)channel).createLinesAsync(new createLines(callContext, transferjournallines)).Result.result;
                        objBOL = SysOperationResults.operationResult<GeneralContract>(results);

                        SysLogUserActivity.logUserActivity(tableName, actionItem, ActionType.Create, objBOL);
                    }
                }

            }
            catch (Exception ex)
            {
                SysErrorLog objErrorLog = new SysErrorLog();
                System.Reflection.MethodBase currentMethod = System.Reflection.MethodBase.GetCurrentMethod();
                string currentMethodName = currentMethod.DeclaringType.FullName;
                objErrorLog.write(currentMethodName, ex);
            }
            finally
            {
            }
            return objBOL;
        }

