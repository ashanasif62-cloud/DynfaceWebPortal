            //JmgProfileTableSvcContract jmgProfileTableSvcContract = new JmgProfileTableSvcContract();
            //jmgProfileTableSvcContract.Profile;
            DataTable dataTable = new DataTable();
            dataTable = RetrieveDatatable.createDataTable(new JmgProfileTableSvcContract[] { });
            return dataTable;
        }

