                    callContext.MessageId = Guid.NewGuid().ToString();
                    callContext.Company = dataAreaId;

                    var results = ((JmgProfileTableSvc)channel).retrieveByEmployeeAsync(new retrieveByEmployee(callContext, _employeeId)).Result.result;

